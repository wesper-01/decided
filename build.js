// Builds the installable Decided web app (iPhone, Android, desktop) from decided.html into app/.
// Run: node build.js  (or npm run build), then host the app folder on any HTTPS host. See app/README.md.
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const here = __dirname, out = path.join(here, 'app');
const src = fs.readFileSync(path.join(here, 'decided.html'), 'utf8');

// The artifact file is head content (title, fonts, styles) followed by the page; split it at the stylesheet's end.
const cut = src.indexOf('</style>') + '</style>'.length;
const head = src.slice(0, cut).replace(/<meta name="claude:[^>]*>\n?/g, '');
const body = src.slice(cut).trim();

const BG_LIGHT = '#E8F1EB', BG_DARK = '#06100C';
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="description" content="Stop deciding. Start changing. Every meal, portion and grocery for your bulk or cut, decided for you.">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Decided">
<meta name="apple-mobile-web-app-status-bar-style" content="default">
<meta name="theme-color" content="${BG_LIGHT}" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="${BG_DARK}" media="(prefers-color-scheme: dark)">
<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<link rel="icon" type="image/png" href="icons/icon-192.png">
<style>body { margin: 0; } [hidden] { display: none !important; }</style>
${head}
</head>
<body>
${body}
<script>
// Offline support, and ask iOS to keep this app's saved data.
if ('serviceWorker' in navigator) addEventListener('load', () => navigator.serviceWorker.register('sw.js').catch(() => {}));
navigator.storage?.persist?.().catch(() => {});
</script>
</body>
</html>
`;

const manifest = {
  name: 'Decided', short_name: 'Decided',
  description: 'Stop deciding. Start changing. Every meal, portion and grocery for your bulk or cut, decided for you.',
  id: './', start_url: './?source=home', scope: './', display: 'standalone', orientation: 'portrait',
  background_color: BG_LIGHT, theme_color: BG_LIGHT,
  icons: [
    { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png' },
    { src: 'icons/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
};

const icons = ['apple-touch-icon.png', 'icon-192.png', 'icon-512.png', 'icon-maskable-512.png'];
for (const i of icons) if (!fs.existsSync(path.join(out, 'icons', i))) throw new Error('Missing app/icons/' + i + ' (run npm run dev and open /__icons to draw them)');

// Each build gets its own cache name, so a new upload replaces the old copy on the phone.
const hash = crypto.createHash('sha1').update(html).update(JSON.stringify(manifest));
for (const i of icons) hash.update(fs.readFileSync(path.join(out, 'icons', i)));
const version = 'bck-' + hash.digest('hex').slice(0, 10);

const sw = `// Offline cache for the Decided home-screen app. Generated by build.js.
const VERSION = '${version}';
const SHELL = ['./', './index.html', './manifest.webmanifest', ${icons.map(i => `'./icons/${i}'`).join(', ')}];
self.addEventListener('install', e => {
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('bck-') && k !== VERSION).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request; if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Fonts never change at a given address: keep the first copy.
  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    e.respondWith(caches.open('fonts-v1').then(async c => (await c.match(req)) || fetch(req).then(r => { if (r.ok || r.type === 'opaque') c.put(req, r.clone()); return r; })));
    return;
  }
  if (url.origin !== location.origin) return;
  // The app itself opens straight from the cache and refreshes in the background for the next launch.
  e.respondWith(caches.open(VERSION).then(async c => {
    const hit = await c.match(req, { ignoreSearch: true });
    const net = fetch(req).then(r => { if (r.ok) c.put(req, r.clone()); return r; }).catch(() => hit || Response.error());
    return hit || net;
  }));
});
`;

fs.writeFileSync(path.join(out, 'index.html'), html);
fs.writeFileSync(path.join(out, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2) + '\n');
fs.writeFileSync(path.join(out, 'sw.js'), sw);
console.log(`Built app/ (${version}): index.html ${Math.round(html.length / 1024)} KB, manifest, sw.js, ${icons.length} icons.`);
